DECLARE
    CURSOR staff_cursor IS
        SELECT NAME, SALARY
        FROM STAFF
        ORDER BY SALARY DESC
        FETCH FIRST 5 ROWS ONLY;

    V_NAME STAFF.NAME%TYPE;
    V_SALARY STAFF.SALARY%TYPE;

BEGIN
    OPEN staff_cursor;

    FETCH staff_cursor INTO V_NAME, V_SALARY;

    WHILE staff_cursor%FOUND LOOP

        DBMS_OUTPUT.PUT_LINE(
            'Name: ' || V_NAME || ', Salary: ' || V_SALARY
        );

        FETCH staff_cursor INTO V_NAME, V_SALARY;

    END LOOP;

    CLOSE staff_cursor;
END;
